export const messages: Record<Locale, Dictionary> = { en, ja, jtp };

export function translate(locale: Locale, key: MessageKey, variables: Record<string, string | number> = {}) {
  return messages[locale][key].replace(/\{(\w+)\}/g, (match, name: string) => String(variables[name] ?? match));
}

export function isLocale(value: unknown): value is Locale {
  return value === "en" || value === "ja" || value === "jtp";
}

export function initialLocale(stored: unknown, browserLanguage: string | undefined): Locale {
  if (isLocale(stored)) return stored;
  return browserLanguage?.toLowerCase().startsWith("ja") ? "ja" : "en";
}

export function htmlLang(locale: Locale) {
  return localeOptions.find((option) => option.id === locale)?.htmlLang ?? "en";
}
